"""CLI for generating entity relationship diagrams (ERD) of the envoy database models using paracelsus.

Requires the "docs" optional dependencies (pip install -e .[docs]) and graphviz (dot) for SVG output.

Reads its paracelsus configuration from the [tool.paracelsus] section of pyproject.toml.

Usage:
    envoy-erd                      # writes docs/erd.md (mermaid) and docs/erd.svg
    envoy-erd --output-dir out/    # writes to a different directory
    envoy-erd --no-svg             # skip the graphviz SVG
    envoy-erd --check              # exit non-zero if the existing files are out of date (writes nothing)

The SVG layout produced by graphviz varies between graphviz versions, so rather than comparing SVG output
byte-for-byte, a SHA256 of the dot source is embedded in the SVG and --check compares against that. This
also means --check does not require graphviz to be installed.
"""

import argparse
import difflib
import hashlib
import re
import shutil
import subprocess  # noqa: S404 # nosec B404
import sys
import sysconfig
from pathlib import Path

DEFAULT_OUTPUT_DIR = Path("docs")
MARKDOWN_FILE_NAME = "erd.md"
SVG_FILE_NAME = "erd.svg"

SVG_HASH_COMMENT_TEMPLATE = "<!-- envoy-erd dot source sha256: {digest} -->"
SVG_HASH_PATTERN = re.compile(r"<!-- envoy-erd dot source sha256: ([0-9a-f]{64}) -->")


def _find_executable(name: str) -> str:
    """Looks for name alongside the current interpreter first (eg a venv) and then on the PATH."""
    scripts_dir = sysconfig.get_path("scripts")
    found = shutil.which(name, path=scripts_dir) or shutil.which(name)
    if found is None:
        raise FileNotFoundError(f"Unable to find '{name}' executable. Is it installed and on the PATH?")
    return found


def run_paracelsus_graph(fmt: str, config: Path) -> str:
    """Equivalent of `paracelsus graph --format {fmt}` - returns the generated graph as a string"""
    result = subprocess.run(  # noqa: S603 # nosec B603
        [_find_executable("paracelsus"), "graph", "--config", str(config), "--format", fmt],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def fix_mermaid(mermaid: str) -> str:
    """Workarounds for paracelsus generating invalid mermaid.

    paracelsus emits multi-word SQL types (eg "DOUBLE PRECISION") verbatim, but mermaid erDiagram attributes are
    "type name [keys]" - the space makes mermaid parse "PRECISION" as the column name and fail on what follows.
    """
    return mermaid.replace("DOUBLE PRECISION", "DOUBLE_PRECISION")


def render_markdown(config: Path) -> str:
    mermaid = fix_mermaid(run_paracelsus_graph("mermaid", config).strip())
    return (
        "# Entity Relationship Diagram\n\n"
        "<!-- Generated by envoy-erd - do not edit manually -->\n\n"
        f"```mermaid\n{mermaid}\n```\n"
    )


def dot_source_digest(dot_source: str) -> str:
    return hashlib.sha256(dot_source.encode()).hexdigest()


def render_svg(dot_source: str) -> str:
    """Equivalent of `dot -Tsvg` with a hash of dot_source embedded as a comment (for --check)"""
    result = subprocess.run(  # noqa: S603 # nosec B603
        [_find_executable("dot"), "-Tsvg"],
        input=dot_source,
        check=True,
        capture_output=True,
        text=True,
    )
    svg = result.stdout
    hash_comment = SVG_HASH_COMMENT_TEMPLATE.format(digest=dot_source_digest(dot_source))

    # Comments can't precede the XML declaration - insert after it (if present)
    if svg.startswith("<?xml"):
        decl_end = svg.index("?>") + 2
        return f"{svg[:decl_end]}\n{hash_comment}{svg[decl_end:]}"
    return f"{hash_comment}\n{svg}"


def check_markdown(output_file: Path, config: Path) -> bool:
    expected = render_markdown(config)
    if not output_file.is_file():
        print(f"{output_file} does not exist", file=sys.stderr)
        return False

    actual = output_file.read_text()
    if actual == expected:
        print(f"{output_file} is up to date")
        return True

    print(f"{output_file} is out of date:", file=sys.stderr)
    diff = difflib.unified_diff(
        actual.splitlines(keepends=True),
        expected.splitlines(keepends=True),
        fromfile=f"{output_file} (current)",
        tofile=f"{output_file} (expected)",
    )
    sys.stderr.writelines(diff)
    return False


def check_svg(output_file: Path, config: Path) -> bool:
    expected_digest = dot_source_digest(run_paracelsus_graph("dot", config))
    if not output_file.is_file():
        print(f"{output_file} does not exist", file=sys.stderr)
        return False

    match = SVG_HASH_PATTERN.search(output_file.read_text())
    if match is None:
        print(f"{output_file} is missing its envoy-erd source hash (was it generated by envoy-erd?)", file=sys.stderr)
        return False

    if match.group(1) != expected_digest:
        print(f"{output_file} is out of date (dot source hash mismatch)", file=sys.stderr)
        return False

    print(f"{output_file} is up to date")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="envoy-erd",
        description="Generate entity relationship diagrams for the envoy database models using paracelsus",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=f"Directory to write the diagrams to (default: {DEFAULT_OUTPUT_DIR})",
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=Path("pyproject.toml"),
        help="pyproject.toml containing the [tool.paracelsus] config (default: ./pyproject.toml)",
    )
    parser.add_argument("--no-markdown", action="store_true", help=f"Skip generating {MARKDOWN_FILE_NAME} (mermaid)")
    parser.add_argument("--no-svg", action="store_true", help=f"Skip generating {SVG_FILE_NAME} (requires graphviz)")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Don't write anything - exit with status 1 if the existing files don't match what would be generated",
    )
    args = parser.parse_args(argv)

    if not args.config.is_file():
        parser.error(f"Config file '{args.config}' not found. Run from the repository root or pass --config.")

    markdown_file: Path = args.output_dir / MARKDOWN_FILE_NAME
    svg_file: Path = args.output_dir / SVG_FILE_NAME

    try:
        if args.check:
            ok = True
            if not args.no_markdown:
                ok = check_markdown(markdown_file, args.config) and ok
            if not args.no_svg:
                ok = check_svg(svg_file, args.config) and ok
            if not ok:
                print("ERD is out of date - run envoy-erd to regenerate", file=sys.stderr)
            return 0 if ok else 1

        args.output_dir.mkdir(parents=True, exist_ok=True)
        if not args.no_markdown:
            markdown_file.write_text(render_markdown(args.config))
            print(f"Wrote {markdown_file}")
        if not args.no_svg:
            svg_file.write_text(render_svg(run_paracelsus_graph("dot", args.config)))
            print(f"Wrote {svg_file}")
    except FileNotFoundError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(f"Error: '{' '.join(exc.cmd)}' failed with exit code {exc.returncode}\n{exc.stderr}", file=sys.stderr)
        return exc.returncode

    return 0


if __name__ == "__main__":
    sys.exit(main())
